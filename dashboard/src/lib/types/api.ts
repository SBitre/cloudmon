/**
 * Shared TypeScript types for the CloudMon read API.
 *
 * These mirror the wire-level contract documented in `docs/event-schema.md`
 * and produced by the read API Lambda (`lambdas/api/handler.py`). Keep this
 * module the single source of truth for shapes that cross the network so
 * consumers (hooks, components) never see `any`.
 */

/**
 * One time-bucket of ingested-event counts, returned by `GET /events/volume`.
 *
 * `minute` is an ISO 8601 UTC timestamp truncated to the start of the minute,
 * e.g. `"2026-05-05T00:21:00Z"`.
 */
export interface VolumeBucket {
  readonly minute: string;
  readonly count: number;
}

/** Response payload for `GET /events/volume`. */
export interface EventsVolumeResponse {
  readonly buckets: readonly VolumeBucket[];
}

/** Severity levels permitted by `docs/event-schema.md`. */
export type Severity = "info" | "warning" | "error" | "critical";

/**
 * One event that contributed to an alert. Mirrors the partial event payload
 * the detection Lambda includes in its alert records.
 */
export interface TriggeringEvent {
  readonly event_id: string;
  readonly timestamp: string;
  readonly service: string;
  readonly event_type: string;
  readonly severity: Severity;
  readonly user_id?: string;
  readonly ip_address?: string;
  readonly endpoint?: string;
  readonly status_code?: number;
  readonly error_message?: string;
}

/**
 * One alert record returned by `GET /alerts`.
 *
 * Generated by the detection Lambda and persisted to the `cloudmon-alerts`
 * DynamoDB table; `explanation` and `recommended_actions` are produced by
 * Gemini and may be empty strings/arrays if the model returned no content.
 */
export interface Alert {
  readonly alert_id: string;
  readonly timestamp: string;
  readonly service: string;
  readonly anomaly_type: string;
  readonly severity: Severity;
  readonly explanation: string;
  readonly recommended_actions: readonly string[];
  readonly triggering_events: readonly TriggeringEvent[];
}

/** Response payload for `GET /alerts`. */
export interface AlertsResponse {
  readonly alerts: readonly Alert[];
}
